#pragma once

#include "lite_common.hpp"

struct EntityID
{
    int32_t index = -1;
    uint32_t gen = 0;

    bool isValid() const;
    bool operator==(const EntityID& other);
};

inline bool EntityID::isValid() const
{
	return (index != -1);
}

inline bool EntityID::operator==(const EntityID& other)
{
    return ((this->index == other.index) && (this->gen == other.gen));
}
